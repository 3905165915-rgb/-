import { chromium } from 'playwright'
import { existsSync } from 'node:fs'
import { mkdir } from 'node:fs/promises'
await mkdir('test-results/product-controls', { recursive: true })
const executablePath = [process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(candidate => candidate && existsSync(candidate))
const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) })
const base = process.env.CONTROLS_TEST_URL || 'http://127.0.0.1:5229/e2e/fixtures/controls.html'
let checks = 0
function assert(condition, message) { if (!condition) throw new Error(message); checks++ }
try {
  for (const width of [320, 390, 430, 1280, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(base)
    const select = page.getByRole('combobox', { name: '班次', exact: true })
    assert(await page.getByLabel('班次', { exact: true }).count() === 1, 'Select field has competing label targets')
    assert(await page.getByLabel('执行时间', { exact: true }).count() === 1, 'Date field has competing label targets')
    await select.click()
    if ([320, 1280].includes(width)) await page.screenshot({ path: `test-results/product-controls/select-${width}.png` })
    await page.getByRole('combobox', { name: '搜索选项' }).fill('早班')
    await page.getByRole('combobox', { name: '搜索选项' }).press('Enter')
    assert(await page.locator('[data-selected]').textContent() === 'S1', `Selection failed at ${width}`)
    assert(await page.locator('[data-changed]').textContent() === 'S1', 'Native change event compatibility failed')
    await page.getByRole('button', { name: '更新名单', exact: true }).click()
    await select.click()
    await page.getByRole('combobox', { name: '搜索选项' }).fill('新增')
    await page.getByRole('option', { name: '新增班次 · 11月4日 08:00–16:00' }).click()
    assert(await page.locator('[data-selected]').textContent() === 'S3', 'Reactive options failed')
    await page.getByRole('button', { name: '执行时间', exact: true }).click()
    await page.getByRole('button', { name: '2026年11月5日', exact: true }).click()
    await page.getByLabel('小时', { exact: true }).fill('9')
    await page.getByRole('button', { name: '关闭日期选择', exact: true }).click()
    assert(await page.locator('[data-date]').textContent() === '2026-11-03T08:30:15', 'Cancel mutated date')
    await page.getByRole('button', { name: '执行时间', exact: true }).click()
    await page.getByRole('button', { name: '2026年11月5日', exact: true }).click()
    await page.getByLabel('小时', { exact: true }).fill('9')
    const bounds = await page.locator('.care-calendar-popup').boundingBox()
    if ([320, 1280].includes(width)) await page.screenshot({ path: `test-results/product-controls/calendar-${width}.png` })
    assert(bounds && bounds.x >= 0 && bounds.x + bounds.width <= width + 1, `Calendar overflow at ${width}`)
    const day = await page.getByRole('button', { name: '2026年11月5日', exact: true }).boundingBox()
    assert(day && day.height >= 44 && day.width >= 43.5, `Calendar touch size at ${width}`)
    await page.getByRole('button', { name: '确认', exact: true }).click()
    assert(await page.locator('[data-date]').textContent() === '2026-11-05T09:30:15', 'Date confirmation mismatch')
    await page.getByRole('button', { name: '执行时间', exact: true }).click()
    await page.getByRole('button', { name: '选择年月', exact: true }).click()
    await page.getByLabel('年份', { exact: true }).fill('2028')
    await page.getByLabel('月份', { exact: true }).fill('2')
    await page.getByRole('button', { name: '转到该月', exact: true }).click()
    await page.getByRole('button', { name: '2028年2月29日', exact: true }).click()
    await page.getByRole('button', { name: '确认', exact: true }).click()
    assert(await page.locator('[data-date]').textContent() === '2028-02-29T09:30:15', 'Year/month jump or leap-day selection failed')
    await page.getByRole('button', { name: '每日时间', exact: true }).click()
    await page.getByLabel('分钟', { exact: true }).fill('45')
    await page.getByRole('button', { name: '确认', exact: true }).click()
    assert(await page.locator('[data-time]').textContent() === '13:45', 'Time confirmation mismatch')
    assert(await page.locator('select,input[type=date],input[type=time],input[type=datetime-local]').count() === 0, 'Native picker remains')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Page overflow at ${width}`)
    assert(errors.length === 0, `Browser errors: ${errors.join('; ')}`)
    await page.close()
  }
  for (const width of [320, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } })
    const queries = []
    await page.route('**/api/v1/options/staff?**', async route => {
      const url = new URL(route.request().url()), offset = Number(url.searchParams.get('offset')), query = url.searchParams.get('q')
      queries.push(url.searchParams)
      const items = query ? [{ id: 'N-result', label: '检索结果 · 合成人员', role: 'nurse' }] : Array.from({ length: offset ? 1 : 50 }, (_, index) => ({ id: 'N' + (index + offset), label: '合成人员' + (index + offset), role: 'nurse' }))
      await route.fulfill({ json: { items, total: query ? 1 : 51, limit: 50, offset } })
    })
    await page.goto(base + '?remote=1')
    const picker = page.getByRole('combobox', { name: '远程责任人', exact: true })
    await picker.click()
    await page.getByRole('button', { name: '加载更多（50 / 51）', exact: true }).click()
    await page.getByRole('option', { name: '合成人员50 · 护士', exact: true }).click()
    assert(await page.locator('[data-remote]').textContent() === 'N50', 'Remote pagination selection failed')
    assert((await picker.textContent()).includes('合成人员50'), 'Selected remote label was lost after closing')
    await picker.click()
    await page.getByRole('combobox', { name: '搜索选项', exact: true }).fill('检索')
    await page.getByRole('option', { name: '检索结果 · 合成人员 · 护士', exact: true }).click()
    assert(await page.locator('[data-remote]').textContent() === 'N-result', 'Remote query selection failed')
    assert(queries.every(params => params.get('shift_id') === 'S1'), 'Selected shift filter was lost')
    assert(queries.some(params => params.get('offset') === '50'), 'Server pagination was not used')
    assert(queries.some(params => params.get('q') === '检索'), 'Server search was not used')
    await page.close()
  }
  process.stdout.write(`${checks} browser control checks passed across 320/390/430/1280/1440px.\n`)
} finally { await browser.close() }
